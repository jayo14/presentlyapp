from django.db import models
from django.conf import settings
from institutions.models import Course, Department, College, Institution


class ReportType(models.TextChoices):
    """Types of reports"""
    ATTENDANCE = 'ATTENDANCE', 'Attendance Report'
    EXAM_CLEARANCE = 'EXAM_CLEARANCE', 'Exam Clearance Report'
    SESSION = 'SESSION', 'Session Report'
    STUDENT = 'STUDENT', 'Student Report'
    COURSE = 'COURSE', 'Course Report'
    DEPARTMENT = 'DEPARTMENT', 'Department Report'


class ReportFormat(models.TextChoices):
    """Export formats"""
    PDF = 'PDF', 'PDF'
    EXCEL = 'EXCEL', 'Excel'
    CSV = 'CSV', 'CSV'


class Report(models.Model):
    """Generated reports"""
    
    title = models.CharField(max_length=200)
    report_type = models.CharField(max_length=20, choices=ReportType.choices)
    format = models.CharField(max_length=10, choices=ReportFormat.choices)
    
    # Filters used to generate the report
    filters = models.JSONField(null=True, blank=True)
    
    # Generated by
    generated_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='generated_reports')
    
    # File details
    file_path = models.CharField(max_length=500, blank=True, null=True)
    file_size = models.IntegerField(null=True, blank=True, help_text="Size in bytes")
    
    # Status
    status = models.CharField(max_length=20, choices=[
        ('PENDING', 'Pending'),
        ('PROCESSING', 'Processing'),
        ('COMPLETED', 'Completed'),
        ('FAILED', 'Failed'),
    ], default='PENDING')
    
    error_message = models.TextField(blank=True, null=True)
    
    # Metadata
    created_at = models.DateTimeField(auto_now_add=True)
    completed_at = models.DateTimeField(null=True, blank=True)
    
    # Expiry (auto-delete after 7 days)
    expires_at = models.DateTimeField(null=True, blank=True)
    
    class Meta:
        db_table = 'reports'
        indexes = [
            models.Index(fields=['generated_by', 'status']),
            models.Index(fields=['report_type']),
            models.Index(fields=['created_at']),
        ]
        ordering = ['-created_at']
    
    def __str__(self):
        return f"{self.title} - {self.format} - {self.status}"


class ScheduledReport(models.Model):
    """Scheduled automatic reports"""
    
    name = models.CharField(max_length=200)
    report_type = models.CharField(max_length=20, choices=ReportType.choices)
    format = models.CharField(max_length=10, choices=ReportFormat.choices)
    
    # Schedule
    frequency = models.CharField(max_length=20, choices=[
        ('DAILY', 'Daily'),
        ('WEEKLY', 'Weekly'),
        ('MONTHLY', 'Monthly'),
        ('SEMESTER', 'End of Semester'),
    ])
    
    # Recipients
    recipients = models.ManyToManyField(settings.AUTH_USER_MODEL, related_name='scheduled_reports')
    
    # Filters
    filters = models.JSONField(null=True, blank=True)
    
    # Schedule details
    scheduled_time = models.TimeField(null=True, blank=True)
    scheduled_day = models.IntegerField(null=True, blank=True, help_text="Day of week (0=Monday) or day of month")
    
    # Status
    is_active = models.BooleanField(default=True)
    last_run = models.DateTimeField(null=True, blank=True)
    next_run = models.DateTimeField(null=True, blank=True)
    
    # Created by
    created_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='created_scheduled_reports')
    
    # Metadata
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    
    class Meta:
        db_table = 'scheduled_reports'
        indexes = [
            models.Index(fields=['is_active', 'next_run']),
            models.Index(fields=['frequency']),
        ]
    
    def __str__(self):
        return f"{self.name} - {self.frequency}"

